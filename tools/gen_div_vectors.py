#!/usr/bin/env python3
"""Generate reference test vectors for div_unit hardware verification."""
import os, random

M = 0xFFFFFFFF
INT_MIN, INT_MAX = 0x80000000, 0x7FFFFFFF


def s32(x):
    return x - (1 << 32) if x & 0x80000000 else x


def model(f, a, b):
    a &= M; b &= M
    if f in (0, 2):                            # signed
        A, B = s32(a), s32(b)
        if B == 0:
            return M if f == 0 else a
        if A == -2**31 and B == -1:
            return INT_MIN if f == 0 else 0
        q = abs(A) // abs(B)
        if (A < 0) != (B < 0):
            q = -q
        return (q if f == 0 else A - q * B) & M
    if b == 0:
        return M if f == 1 else a
    return a // b if f == 1 else a % b


# (group id, case name, [(a, b), ...]) - every pair runs with all four ops
GROUPS = [
    (1,  "A1 divide by zero, positive dividend", [(7, 0), (1, 0), (INT_MAX, 0)]),
    (2,  "A2 divide by zero, negative dividend", [(-7, 0), (-1, 0)]),
    (3,  "A3 zero divided by zero",              [(0, 0)]),
    (4,  "A4 INT_MIN / 0",                       [(INT_MIN, 0)]),
    (5,  "A5 signed overflow INT_MIN / -1",      [(INT_MIN, -1)]),
    (6,  "A6 0x80000000 / 0xFFFFFFFF",           [(0x80000000, 0xFFFFFFFF)]),
    (7,  "A7 INT_MIN by +-1, +-2, INT_MIN, INT_MAX",
         [(INT_MIN, 1), (INT_MIN, -1), (INT_MIN, 2), (INT_MIN, -2), (INT_MIN, INT_MIN), (INT_MIN, INT_MAX)]),
    (8,  "A8 INT_MIN+1 / -1",                    [(INT_MIN + 1, -1)]),
    (9,  "A9 zero dividend",                     [(0, 7), (0, -7), (0, 1), (0, INT_MIN)]),
    (10, "A10 divide by 1 and by -1",            [(7, 1), (7, -1), (-7, 1), (-7, -1), (0x12345678, 1), (0x12345678, -1)]),
    (11, "A11 divisor larger than dividend",     [(3, 7), (-3, 7), (3, -7), (1, INT_MAX)]),
    (12, "A12 dividend equals divisor",          [(7, 7), (-7, -7), (INT_MAX, INT_MAX), (0x12345678, 0x12345678)]),
    (13, "A13 remainder sign follows dividend",  [(-7, 2), (7, -2)]),
    (14, "A14 all four sign combinations",       [(7, 2), (-7, 2), (7, -2), (-7, -2)]),
    (15, "A15 exact negative quotient",          [(-6, 3), (6, -3), (-6, -3)]),
    (16, "A16 0xFFFFFFFF signed vs unsigned",    [(0xFFFFFFFF, 2)]),
    (17, "A17 largest dividend, divisor 1",      [(0xFFFFFFFF, 1)]),
    (18, "A18 divisor with top bit set",         [(0x7FFFFFFF, 0x80000000), (0x80000000, 0x80000000), (0xFFFFFFFF, 0x80000000)]),
    (19, "A19 divisor every power of two",       [(0xFFFFFFFF, 1 << j) for j in range(32)]),
    (20, "A20 dividend every power of two",      [(1 << j, 3) for j in range(32)]),
    (21, "A21 half-word patterns",
         [(0x00010000, 0xFFFF0000), (0xFFFF0000, 0x00010000), (0x00010000, 3), (0xFFFF0000, -3)]),
]

CORNERS = [0, 1, -1, INT_MIN, INT_MAX, 7, -7, 2, -2, 0x12345678,
           INT_MIN + 1, INT_MAX - 1, 0x00010000, 0xFFFF0000, 3, -3]
GROUPS.append((22, "corner grid 16 x 16", [(x, y) for x in CORNERS for y in CORNERS]))
GROUPS.append((23, "small exhaustive -10..10", [(x, y) for x in range(-10, 11) for y in range(-10, 11)]))
rng = random.Random(2026)                       # fixed seed: same file every run
rnd = []
for i in range(400):
    a, b = rng.getrandbits(32), rng.getrandbits(32)
    if i % 4 == 1: b &= 0xFF
    if i % 4 == 2: b = s32(b & 0xF | (0xFFFFFFF0 if b & 8 else 0))
    rnd.append((a, b))
GROUPS.append((24, "random 400", rnd))

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "ooo_tests", "vectors")
os.makedirs(out, exist_ok=True)
n = 0
with open(os.path.join(out, "div_unit_vectors.mem"), "w") as mem:
    mem.write("// group funct3 a b expected  (generated by tools/gen_div_vectors.py)\n")
    for gid, name, pairs in GROUPS:
        mem.write(f"// {gid}: {name}\n")
        for a, b in pairs:
            for f in range(4):
                a32, b32 = a & M, b & M
                e = model(f, a32, b32)
                mem.write(f"{gid:08x} {f:08x} {a32:08x} {b32:08x} {e:08x}\n")
                n += 1
print(f"wrote {n} vectors in {len(GROUPS)} groups to {os.path.normpath(out)}")
